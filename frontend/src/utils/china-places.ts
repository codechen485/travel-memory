/** 省份全称后缀（用于剥离得到简称） */
const PROVINCE_SUFFIXES = ['维吾尔自治区', '壮族自治区', '回族自治区', '自治区', '特别行政区', '省', '市']

/** 省份全称 → 简称 */
function provinceShort(full: string): string {
  for (const s of PROVINCE_SUFFIXES) {
    if (full.endsWith(s)) return full.slice(0, -s.length)
  }
  return full
}

/** 预排序（长名优先，保证「最长匹配」） */
const CITY_KEYS = Object.keys(CITY_COORDS).sort((a, b) => b.length - a.length)
const ALIAS_KEYS = Object.keys(ALIASES).sort((a, b) => b.length - a.length)
const PROVINCE_ENTRIES = Object.entries(PROVINCE_CENTROID)
  .map(([full, c]) => ({ full, short: provinceShort(full), lng: c[0], lat: c[1] }))
  .sort((a, b) => b.short.length - a.short.length)

/**
 * 把一段自由文本目的地解析成坐标 + 省份。
 * 匹配优先级：景区别名 → 城市（最长包含匹配）→ 省份（用省会坐标兜底）。
 * 无法识别返回 null（调用方可跳过或计入「未识别」）。
 */
export function resolvePlace(raw: string | null | undefined): ResolvedPlace | null {
  const s = (raw ?? '').trim()
  if (!s) return null

  // 1. 景区/地标别名
  for (const alias of ALIAS_KEYS) {
    if (s.includes(alias)) {
      const city = ALIASES[alias]!
      const e = CITY_COORDS[city]
      if (e) return { lng: e[0], lat: e[1], province: e[2], cityName: city }
    }
  }

  // 2. 城市（最长包含匹配，兼容「南京市」「江苏省南京市」「南京梧桐大道」）
  for (const key of CITY_KEYS) {
    if (s.includes(key)) {
      const e = CITY_COORDS[key]!
      return { lng: e[0], lat: e[1], province: e[2], cityName: key }
    }
  }

  // 3. 省份（用省会坐标兜底）
  for (const p of PROVINCE_ENTRIES) {
    if (s.includes(p.short) || s.includes(p.full)) {
      return { lng: p.lng, lat: p.lat, province: p.full, cityName: p.short }
    }
  }

  return null
}
